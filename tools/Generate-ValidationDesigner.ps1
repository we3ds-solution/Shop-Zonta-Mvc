$ErrorActionPreference = "Stop"
# Regenerates market-mvc/Resources/SharedValidation.Designer.cs from the .en resx key list.
# Run from the repository root after adding/removing resx keys:
#   powershell -ExecutionPolicy Bypass -File tools/Generate-ValidationDesigner.ps1
# Deterministic and offline. The Designer provides the public static string
# properties that DisplayAttribute/ValidationAttribute resource lookup requires.
$root = Join-Path $PSScriptRoot "../market-mvc/Resources"
[xml]$xml = Get-Content (Join-Path $root "SharedValidation.en.resx") -Encoding UTF8
$names = $xml.root.data | ForEach-Object { $_.name } | Sort-Object -Unique
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// <auto-generated />")
[void]$sb.AppendLine("// Regenerate with tools/Generate-ValidationDesigner.ps1 after resx changes.")
[void]$sb.AppendLine("using System.Globalization;")
[void]$sb.AppendLine("using System.Resources;")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("namespace market_mvc.Resources")
[void]$sb.AppendLine("{")
[void]$sb.AppendLine("    public sealed class SharedValidation")
[void]$sb.AppendLine("    {")
[void]$sb.AppendLine("        private static ResourceManager? _manager;")
[void]$sb.AppendLine('        internal static ResourceManager Manager => _manager ??= new ResourceManager("market_mvc.Resources.SharedValidation", typeof(SharedValidation).Assembly);')
[void]$sb.AppendLine("        private SharedValidation() { }")
foreach ($n in $names) {
    $safe = $n -replace '[^A-Za-z0-9_]', '_'
    [void]$sb.AppendLine("")
    [void]$sb.AppendLine("        public static string " + $safe + " => Manager.GetString(`"" + $n + "`", CultureInfo.CurrentUICulture) ?? `"[" + $n + "]`";")
}
[void]$sb.AppendLine("    }")
[void]$sb.AppendLine("}")
[System.IO.File]::WriteAllText((Join-Path $root "SharedValidation.Designer.cs"), $sb.ToString(), [System.Text.UTF8Encoding]::new($false))
Write-Output ("designer written with " + $names.Count + " properties")
